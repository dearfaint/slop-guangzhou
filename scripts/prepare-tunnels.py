# coding: utf-8
"""Build the six named motor underpasses from packaged OSM geometry.
Source tunnel tags delimit covered sections; adjacent source ways provide approach ramps.
Vertical dimensions are estimates, not surveyed elevations.
"""
import json, math, pathlib
from shapely.geometry import LineString, Polygon, Point
from shapely.ops import unary_union
ROOT=pathlib.Path(__file__).resolve().parents[1]
from static_data import write_static_data  # noqa: E402  (scripts/ is on sys.path when run directly)
root=ROOT/'public/data'
read=lambda p:json.loads(p.read_text())
tiles=[read(root/(t['id']+'.json')) for t in read(root/'manifest.json')['tiles']]
roads={r['id']:r for t in tiles for r in t['roads']}
NAMES=['广州大道珠江新城隧道','黄埔大道隧道','金穗路隧道','CBD隧道','猎德大道-金穗路隧道','花城大道隧道']
key=lambda p:(round(p[0]*2),round(p[1]*2))
by_node={}
for r in roads.values():
 for p in r['p']:by_node.setdefault(key(p),{})[r['id']]=r
covered={r['id']:r for r in roads.values() if r['tunnel'] and r['name'] in NAMES}
ramps={}
for r in covered.values():
 for p in [r['p'][0],r['p'][-1]]:
  for q in by_node[key(p)].values():
   if not q['bridge'] and not q['tunnel'] and q.get('layer',0)==0 and q['kind'] in ['trunk','primary','secondary']:
    ramps.setdefault(q['id'],{'road':q,'ends':set(),'name':r['name']})['ends'].add(key(p))
def polygons(g):
 if g.is_empty:return []
 if g.geom_type=='Polygon':return [g]
 return [p for child in getattr(g,'geoms',[]) for p in polygons(child)]
def lines(g):
 if g.is_empty:return []
 if g.geom_type=='LineString':return [g]
 return [p for child in getattr(g,'geoms',[]) for p in lines(child)]
def coords(g):return [[round(x,3),round(z,3)] for x,z in g.coords]
def rings(g):return [coords(q) for q in [g.exterior,*g.interiors]]
profiles=[]
for r in [*covered.values(),*[q['road'] for q in ramps.values()]]:
 line=LineString(r['p']);stations={0,line.length}
 for p in r['p']:stations.add(line.project(Point(p)))
 stations.update(line.length*i/math.ceil(line.length/3) for i in range(math.ceil(line.length/3)+1))
 stations=sorted(stations);p=[[round(line.interpolate(s).x,4),round(line.interpolate(s).y,4)] for s in stations]
 is_covered=r['id'] in covered
 ends=ramps[r['id']]['ends'] if not is_covered else set()
 ramp_len=min(100,max(1,line.length-12))
 def smooth(t):
  t=max(0,min(1,t));return t*t*(3-2*t)
 y=[-5.65 if is_covered else round(.35-6*max([smooth(1-(s if k==key(r['p'][0]) else line.length-s)/ramp_len) for k in ends]),4) for s in stations]
 profiles.append(dict(id=r['id'],name=r['name'] if is_covered else ramps[r['id']]['name'],p=p,y=y,w=r['w'],covered=is_covered))
# Open ramp trenches form one union; covered tunnel roofs stay beneath the intact city surface.
trenches=[]
for r in profiles:
 if r['covered']:continue
 for i in range(1,len(r['p'])):
  if min(r['y'][i-1:i+1])<-.22:trenches.append(LineString(r['p'][i-1:i+1]).buffer(r['w']/2+.35,cap_style=2,join_style=2))
mask=unary_union(trenches)
for r in profiles:
 line=LineString(r['p']);source=roads[r['id']];nodes={key(p) for p in source['p']}
 neighbors=[LineString(q['p']).buffer(q['w']/2+.18,cap_style=1,join_style=2) for q in profiles if q is not r and nodes.intersection({key(p) for p in roads[q['id']]['p']})]
 openings=unary_union(neighbors)
 r['walls']=[coords(q) for side in [-1,1] for q in lines(line.offset_curve(side*(r['w']/2+.12),join_style=2).difference(openings))]
road_surfaces={};area_surfaces={}
profile_ids={r['id'] for r in profiles}
for r in roads.values():
 if r['id'] in profile_ids or r['tunnel'] or r['bridge'] or r.get('layer',0)<0:continue
 line=LineString(r['p']);surface=line.buffer(r['w']/2,cap_style=2,join_style=2)
 if surface.intersects(mask):
  road_surfaces[r['id']]={'p':[rings(p) for p in polygons(surface.difference(mask)) if p.area>.05],'lines':[coords(q) for q in lines(line.difference(mask.buffer(r['w']/2))) if q.length>.1]}
for t in tiles:
 for a in t['areas']:
  surface=Polygon(a['p'][0],a['p'][1:])
  if surface.intersects(mask):area_surfaces[f"{a['p'][0][0][0]:g}:{a['p'][0][0][1]:g}:{a['name']}"]=[rings(p) for p in polygons(surface.difference(mask))]
result={'routes':profiles,'excavations':[rings(p) for p in polygons(mask)],'roadSurfaces':road_surfaces,'areaSurfaces':area_surfaces}
write_static_data(ROOT,'tunnel-data',result,comment='Generated by scripts/prepare-tunnels.py from packaged OSM paths; heights are visual estimates.',export='tunnelData',type_='TunnelData',type_imports="import type {TunnelData} from './tunnel-layout.ts';\n")
print(f'{len(covered)} covered sections, {len(ramps)} approach roads, {len(result["excavations"])} excavations')
