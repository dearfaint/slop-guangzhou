"""Continuous inferred ground paving around ordinary source roads. No map edits."""
import json
import subprocess
from pathlib import Path
from shapely.geometry import Polygon, LineString, box
from shapely.ops import unary_union, nearest_points
from shapely.strtree import STRtree
ROOT = Path(__file__).resolve().parents[1]
from static_data import write_static_data  # noqa: E402  (scripts/ is on sys.path when run directly)
def node(script, *args):
    return json.loads(subprocess.check_output(['node', str(ROOT / 'scripts' / script), *args], text=True))
source = node('street-paving-input.mjs')
walk = {'footway', 'path', 'pedestrian', 'steps', 'cycleway'}
paths = [(r, LineString(p)) for r in source['roads'] for p in r['paths'] if len(p) > 1]
foot = [line for r, line in paths if r['kind'] in walk]
foot_index = STRtree(foot)
# Source widths remain unchanged. A narrow apron joins independent ribbons; it
# does not extend the motor network or create obstacles in the median.
aprons = [line.buffer(r['w'] / 2 + (1 if r['kind'] in walk else 3), join_style=2) for r, line in paths]
landings = []
for c in source['crossings']:
    # Each paint stripe spans the road direction. Its two walking ends face
    # neighbouring sidewalks, so a landing can connect an offset mapped path.
    for side in [-1, 1]:
        p = LineString([(c['x'] - c['dz'] * c['width'] / 2 * side, c['z'] + c['dx'] * c['width'] / 2 * side),
                        (c['x'] - c['dz'] * (c['width'] / 2 + 3) * side, c['z'] + c['dx'] * (c['width'] / 2 + 3) * side)])
        a = p.boundary.geoms[1]
        if foot:
            line = foot[int(foot_index.nearest(a))]
            if a.distance(line) <= 10:
                q = nearest_points(a, line)[1]
                p = LineString([p.coords[0], a.coords[0], q.coords[0]])
        landings.append(p.buffer(1.5, join_style=2))
exclusions = node('forecourt-exclusions.mjs', '--paving')
protected = unary_union([Polygon(p[0], p[1:]).buffer(0) for p in exclusions])
manifest = json.loads((ROOT / 'public/data/manifest.json').read_text())
data = [json.loads((ROOT / 'public/data' / (t['id'] + '.json')).read_text()) for t in manifest['tiles']]
# Preserve water, source green space, buildings, authored sites and bridge ramps.
obstacles = [Polygon(b['p'][0], b['p'][1:]).buffer(.1) for t in data for b in t['buildings'] if b.get('base', 0) < 2 and b['id'] not in source['hiddenBuildings']]
obstacles += [Polygon(a['p'][0], a['p'][1:]).buffer(0) for t in data for a in t['areas']]
obstacles += [LineString(r['p']).buffer(r['w'] / 2 + .2) for t in data for r in t['roads'] if r['bridge']]
# Paving stays under the asphalt, rather than crossing over its paint or making
# a raised pedestrian bar across the carriageway.
asphalt = []
for r in source['roads']:
    if r['kind'] in walk:
        continue
    if r.get('surfaces') is not None:
        asphalt += [Polygon(p[0], p[1:]).buffer(0) for p in r['surfaces']]
    else:
        asphalt += [LineString(p).buffer(r['w'] / 2, join_style=2) for p in r['paths'] if len(p) > 1]
blocked = unary_union([protected, *obstacles, *asphalt])
# At the east entrance, the existing building forecourt closes the pockets beside the U-shaped walkway.
# Include that edge when finding enclosed gaps, instead of extending a guessed-width path buffer.
forecourts = unary_union([Polygon(p[0], p[1:]).buffer(0) for p in source['forecourtPaving']])
entrance_bounds = box(-258, -180, -168, -48)
joined = unary_union([*aprons, *landings, forecourts.intersection(entrance_bounds)])
# Small enclosed gaps between the mapped ribbons are part of the same street
# island. Keep large blocks open; all source areas are still subtracted below.
parts = [joined] if joined.geom_type == 'Polygon' else list(joined.geoms)
joined = unary_union([Polygon(p.exterior, [r for r in p.interiors if Polygon(r).area > 3000]) for p in parts])
surface = joined.difference(blocked).buffer(0)
def polygons(g):
    if g.geom_type == 'Polygon':
        return [g]
    return [p for p in getattr(g, 'geoms', []) if p.geom_type == 'Polygon']
def rings(g):
    return [[[[round(x, 3), round(z, 3)] for x, z in ring.coords] for ring in [p.exterior, *p.interiors]] for p in polygons(g.simplify(.025, preserve_topology=True)) if p.area > .05]
# Use the adjoining forecourt's slab finish for these entrance pockets rather than bare apron colour.
entrance_plaza = surface.intersection(entrance_bounds).difference(forecourts)
result = []
for t in source['tiles']:
    bounds = box(*t['bounds'])
    tile = {'roads': t['roads'], 'p': rings(surface.intersection(bounds))}
    plaza = rings(entrance_plaza.intersection(bounds))
    if plaza:
        tile['plaza'] = plaza
    result.append(tile)
write_static_data(ROOT, 'street-paving-data', result, ensure_ascii=True, comment='Generated by scripts/prepare-street-paving.py; inferred visual paving, source roads unchanged.', export='streetPavingData', type_='{roads:string[];p:Point[][][];plaza?:Point[][][]}[]', type_imports="import type {Point} from './types.ts';\n")
print(json.dumps({'tiles': len(result), 'polygons': sum(len(t['p']) for t in result), 'area': round(surface.area)}))
