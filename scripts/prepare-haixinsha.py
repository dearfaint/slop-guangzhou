"""Extract existing WGS84 source footprints; model elevations are documented estimates."""
import json, math, pathlib
from shapely.geometry import Polygon, LineString, Point
from shapely.ops import unary_union
root=pathlib.Path(__file__).resolve().parents[1]
raw=json.loads((root/'data/raw/osm.json').read_text())
ways={e['id']:e for e in raw['elements'] if e['type']=='way'}
def project(p):return [round((p['lon']-113.322)*math.pi/180*6378137*math.cos(math.radians(23.119)),3),round(-(p['lat']-23.119)*math.pi/180*6378137,3)]
def outline(i):return [project(p) for p in ways[i]['geometry']]
def rings(poly):return [[[round(x,3),round(z,3)] for x,z in ring.coords] for ring in [poly.exterior,*poly.interiors]]
def polygons(g):
 if g.is_empty:return []
 if g.geom_type=='Polygon':return [g]
 return [p for c in getattr(g,'geoms',[]) for p in polygons(c)]
manifest=json.loads((root/'public/data/manifest.json').read_text())
all_buildings={b['id']:b for t in manifest['tiles'] for b in json.loads((root/('public/data/'+t['id']+'.json')).read_text())['buildings']}
buildings=[];hidden=[]
for b in all_buildings.values():
 p=b['p'][0];x=sum(v[0] for v in p)/len(p);z=sum(v[1] for v in p)/len(p)
 if not (-700<x<275 and 455<z<675):continue
 if b['name']=='海心沙':hidden.append(b['id']);continue # underground APM station
 kind='stand' if x<-400 else 'hotel' if x>0 else 'service'
 height=(51 if 'ac999b62' in b['id'] else 5) if kind=='stand' else 12 if kind=='hotel' else 7
 buildings.append(dict(id=b['id'],p=b['p'],h=height,kind=kind))
# Bridge decks retain their source outlines; do not add synthetic circular bank patches.
bridges=[
 dict(id=1372988680,name=ways[1372988680]['tags']['name'],p=[outline(1372988680)],h=5),
 dict(id=858784087,name=ways[858784087]['tags']['name'],p=[outline(858784087)],h=5),
 dict(id=1372988681,name=ways[1372988681]['tags']['name'],p=[outline(1372988681)],h=5),
 dict(id=1372988682,name=ways[1372988682]['tags']['name'],p=[outline(1372988682)],h=5),
]

# Haixin Bridge: preserve original polygon in p[0] while generating branch landings in branches:
poly1313=Polygon(outline(1313608038))
s898=LineString(outline(898186209))
l461=LineString(outline(1024168461))
s462=LineString(outline(1024168462))
l459_pts=outline(1024168459)

nw_ramp=unary_union([
 s898.buffer(7.5,cap_style=1,join_style=2),
 l461.buffer(7.0,cap_style=2,join_style=2),
 Point(-908.47,786.46).buffer(8.5)
]).difference(poly1313)

sw_ramp=unary_union([
 s462.buffer(7.0,cap_style=1,join_style=2),
 Point(-828.21,1034.35).buffer(8.5)
]).difference(poly1313)

se_ext=unary_union([
 LineString(l459_pts[-10:]).buffer(7.5,cap_style=1,join_style=2),
 Point(-657.71,1008.73).buffer(9.0)
]).difference(poly1313)

ne_ext=unary_union([
 LineString(l459_pts[:10]).buffer(7.5,cap_style=1,join_style=2),
 Point(-742.56,733.38).buffer(8.5)
]).difference(poly1313)

haixin_branches=[rings(p) for p in polygons(unary_union([nw_ramp,sw_ramp,se_ext,ne_ext])) if p.area>5]

haixin_dict=dict(
 id=1313608038,
 p=[outline(1313608038)],
 path=outline(1024168459),
 branches=haixin_branches,
 branchPaths=[outline(898186209),outline(1024168461),outline(1024168462)]
)
data=dict(pools=[dict(id=i,p=[outline(i)]) for i in [511475341,511475342]],island=[outline(29167398)],buildings=buildings,hidden=hidden,bridges=bridges,haixin=haixin_dict,source='Existing OSM / Overture snapshot; user map reference 2026-10-24. Heights and facade details are visual estimates.')
(root/'src/haixinsha-data.ts').write_text("// Generated by scripts/prepare-haixinsha.py; do not infer surveyed elevations.\nimport type { Point } from './types.ts';\nexport interface IslandBuilding {id:string;p:Point[][];h:number;kind:string}\nexport interface HaixinBridge {id:number;name:string;p:Point[][];h:number}\nexport interface HaixinStructure {id:number;p:Point[][];path:Point[];branches?:Point[][][];branchPaths?:Point[][]}\nexport const haixinshaData:"+"{pools:{id:number;p:Point[][]}[];island:Point[][];buildings:IslandBuilding[];hidden:string[];bridges:HaixinBridge[];haixin:HaixinStructure;source:string}="+json.dumps(data,ensure_ascii=False,separators=(',',':'))+';\n')
